    private class Seed(
        val english: String,
        val meaning: String,
        val example: String,
        val exampleFa: String,
        val phonetic: String,
        val pos: String,
        val topic: String,
    ) {
        fun toWord(now: LocalDateTime) = Word(
            english = english,
            meaning = meaning,
            example = example,
            exampleFa = exampleFa,
            phonetic = phonetic,
            partOfSpeech = pos,
            topic = topic,
            nextReviewAt = now.plusMinutes(10),
            createdAt = now,
        )
    }

